/* =====================================================
   قائمة المنتجات — هذا هو الملف الوحيد الذي تعدّله لإضافة منتج
   =====================================================
 
   لإضافة منتج جديد:
   1) ضع صورته في مجلد imgs (يفضّل PNG بخلفية شفافة).
   2) انسخ أي منتج من القائمة بالأسفل بالكامل (من { إلى },) والصقه
      قبل علامة ] ثم غيّر بياناته.
   3) انتبه أن ينتهي كل منتج بـ  },  وكل سطر داخله بفاصلة (,).
 
   حقول المنتج:
     src       مسار الصورة                         (مطلوب)
     name      اسم المنتج (العنوان الكبير)
     desc      الشرح تحت العنوان
     oldPrice  السعر القديم (المشطوب)، مثل '25$'
               اكتب oldPrice: '' ليظهر السعر الجديد وحده (ولا يظهر القديم إن ساوى الجديد)
     price     السعر الجديد، مثل '20$'
     features  قائمة الميزات (أي عدد، والأفضل 5)
     glow      لون التوهج في الوسط (اختياري)
     base      لون أطراف الخلفية   (اختياري)

     --- العرض (شارة أعلى يمين المنتج، اختياري) ---
     offer       true لتفعيل العرض على هذا المنتج. احذف السطر أو اكتب false لإلغائه
                 (ويمكن كتابة نص العرض مباشرة:  offer: 'خصم 20%')
     offerText   نص العرض الكبير، مثل 'خصم 20%' أو 'وفّر 15$' أو 'اشترِ 2 والثالثة مجاناً'
     offerLabel  العنوان الصغير فوق النص (اختياري، الافتراضي: 'عرض خاص')

   ملاحظات:
   - أي حقل تتركه بدون كتابة يأخذ القيمة المكتوبة في index.html.
   - إذا لم تكتب glow و base تُستخدم ألوان احتياطية فاتحة هادئة، وتتحول النصوص للغامق تلقائياً.
   - الصورة الأولى في القائمة هي التي تظهر عند فتح الموقع.
   - إذا أخطأت في اسم صورة فلن يتعطل الموقع، سيتجاهل ذلك المنتج
     ويكتب تنبيهاً في Console (اضغط F12 لرؤيته).
   - يمكن كتابة منتج بدون أي نص هكذا فقط:  'imgs/05.png',
   - لا تغيّر اسم القائمة PRODUCTS.
*/
 
